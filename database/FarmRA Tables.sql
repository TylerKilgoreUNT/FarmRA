--Table Creation Script
DO $TCS$
BEGIN

    DROP TABLE IF EXISTS node_data.measurements;
    DROP TABLE IF EXISTS node_data.nodes;
    DROP TABLE IF EXISTS node_data.gateways;
    DROP TABLE IF EXISTS user_data.users;

    --SCHEMA: user_data
    SET SEARCH_PATH to user_data;

    CREATE TABLE users
    (
        u_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
        u_f_name VARCHAR(32) NOT NULL,
        u_l_name VARCHAR(32) NOT NULL,
        u_email VARCHAR(64) NOT NULL,
        u_role VARCHAR(8) NOT NULL,
        
        CONSTRAINT users_pk PRIMARY KEY(u_id)
    );

    --SCHEMA: node_data
    SET SEARCH_PATH to node_data;

    CREATE TABLE gateways
    (
        g_id VARCHAR(32) NOT NULL,
        u_id_fk INTEGER,

        CONSTRAINT gateways_pk PRIMARY KEY(g_id),
        CONSTRAINT users_fk FOREIGN KEY(u_id_fk) 
                        REFERENCES user_data.users(u_id)
    );

    CREATE TABLE nodes
    (
        n_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
        g_id_fk VARCHAR(32) NOT NULL,
        n_name VARCHAR(32) NOT NULL,
        
        CONSTRAINT nodes_pk PRIMARY KEY(n_id),
        CONSTRAINT gateways_fk FOREIGN KEY(g_id_fk) 
                        REFERENCES node_data.gateways(g_id)
    );

    CREATE TABLE measurements
    (
        m_time TIMESTAMPTZ NOT NULL,
        n_id_fk INTEGER NOT NULL,
        m_temperature DOUBLE PRECISION,
        m_moist INT,
        m_light INT,
        m_batt INT,
        
        CONSTRAINT nodes_fk FOREIGN KEY(n_id_fk) 
                        REFERENCES node_data.nodes(n_id)
    );

    SELECT create_hypertable('test_measurements', 'm_time');

END $TCS$;

